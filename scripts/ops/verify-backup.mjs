/**
 * Independent, cross-platform INTEGRITY + STRUCTURAL-COMPLETENESS verification
 * of a Forge backup. It does NOT perform a restore, so it does not prove
 * restorability — it proves the file is intact and structurally complete.
 *
 *   node scripts/ops/verify-backup.mjs <path-to-backup.sql.gz>
 *
 * forge-backup.sh verifies a dump AT CREATION time using the MariaDB client in
 * a container. This re-verifies an EXISTING backup with no database, no Docker
 * and no shell tools, so the deploy can gate on a second, independent check.
 *
 * Streaming (bounded memory, V4): the compressed file is hashed as a stream and
 * the decompressed dump is scanned line-by-line — the whole dump is never held
 * in memory.
 *
 * Checks:
 *   - exists and non-empty;
 *   - VALID gzip over the WHOLE stream (gunzip errors ⇒ truncated/corrupt);
 *   - ends with the mariadb-dump "-- Dump completed" marker;
 *   - all 46 Forge tables present as CREATE TABLE (forge_ or legacy names);
 *   - NO DROP TABLE / DROP DATABASE;
 *   - DATA PRESENCE (V2): if a `<base>-hashes.json` sidecar exists (independently
 *     generated by table-hashes.mjs), every table it records with rows > 0 must
 *     have INSERT data in the dump; empty tables are allowed. Without the sidecar,
 *     data presence is reported as unverified (not failed);
 *   - if a `<file>.sha256` sidecar exists, the file's sha256 matches it.
 *
 * Never prints dump contents — only counts, markers and booleans.
 */
import { existsSync, statSync, createReadStream, readFileSync } from 'node:fs'
import { createGunzip } from 'node:zlib'
import { createHash } from 'node:crypto'
import { createInterface } from 'node:readline'
import { pathToFileURL } from 'node:url'
import { LOGICAL_TABLES, TABLE_RENAMES } from '../../src/lib/queries/tables.mjs'

/** sha256 of the file, streamed (never loads it all into memory). */
async function sha256File(file) {
  const h = createHash('sha256')
  for await (const chunk of createReadStream(file)) h.update(chunk)
  return h.digest('hex')
}

/**
 * Verify a backup file. Async + streaming; returns { ok, problems, notes }.
 */
export async function verifyBackup(file) {
  const problems = []
  const notes = []

  if (!existsSync(file)) return { ok: false, problems: [`file not found: ${file}`], notes: [] }
  if (statSync(file).size === 0) return { ok: false, problems: ['file is empty'], notes: [] }

  // Scan the decompressed dump line-by-line (bounded memory).
  const created = new Set()
  const inserted = new Set()
  let hasDrop = false
  let lastNonEmpty = ''
  try {
    const rl = createInterface({ input: createReadStream(file).pipe(createGunzip()), crlfDelay: Infinity })
    for await (const line of rl) {
      if (line.trim() !== '') lastNonEmpty = line
      let m
      if ((m = line.match(/^CREATE TABLE\s+`?([A-Za-z0-9_$]+)`?/i))) created.add(m[1])
      else if ((m = line.match(/^INSERT INTO\s+`?([A-Za-z0-9_$]+)`?/i))) inserted.add(m[1])
      else if (/^\s*DROP\s+(TABLE|DATABASE)\b/i.test(line)) hasDrop = true
    }
  } catch (e) {
    return { ok: false, problems: [`not a valid gzip / truncated: ${e.code || e.message}`], notes: [] }
  }

  if (!/^-- Dump completed/.test(lastNonEmpty)) problems.push('dump is incomplete (no "-- Dump completed" marker at end)')
  if (hasDrop) problems.push('contains a DROP TABLE/DATABASE statement (refused)')

  const missing = LOGICAL_TABLES.filter((l) => !created.has(TABLE_RENAMES[l]) && !created.has(l))
  if (missing.length) problems.push(`missing ${missing.length} Forge table(s): ${missing.slice(0, 5).join(', ')}${missing.length > 5 ? ', …' : ''}`)
  notes.push(`${created.size} CREATE TABLE, ${LOGICAL_TABLES.length - missing.length}/${LOGICAL_TABLES.length} Forge tables present`)

  // Data presence (V2): cross-check against the independently generated hashes JSON.
  const hashesFile = `${file.replace(/\.sql\.gz$/, '')}-hashes.json`
  if (existsSync(hashesFile)) {
    try {
      const h = JSON.parse(readFileSync(hashesFile, 'utf8'))
      const entries = Object.entries(h)
      let expectedRows = 0
      const noInsert = []
      let reportedMissing = 0
      for (const [, v] of entries) {
        if (v && v.missing) { reportedMissing += 1; continue }
        if (v && typeof v.rows === 'number') {
          expectedRows += v.rows
          if (v.rows > 0 && !inserted.has(v.table)) noInsert.push(`${v.table}(${v.rows})`)
        }
      }
      if (entries.length < LOGICAL_TABLES.length) problems.push(`content-hash JSON covers only ${entries.length}/${LOGICAL_TABLES.length} tables`)
      if (reportedMissing) problems.push(`content-hash JSON reports ${reportedMissing} missing table(s)`)
      if (noInsert.length) problems.push(`tables with rows per content-hash but NO INSERT data in the dump: ${noInsert.slice(0, 5).join(', ')}${noInsert.length > 5 ? ', …' : ''}`)
      notes.push(`content-hash JSON: ${entries.length} tables, ${expectedRows} expected rows; ${inserted.size} table(s) with INSERT data in the dump`)
    } catch (e) {
      problems.push(`content-hash JSON is invalid: ${e.message}`)
    }
  } else {
    notes.push(`data presence NOT independently verified (no content-hash JSON sidecar); dump has INSERT data for ${inserted.size} table(s)`)
  }

  // sha256 sidecar (corruption/tamper detection; absence is allowed).
  const shaFile = `${file}.sha256`
  if (existsSync(shaFile)) {
    const expected = readFileSync(shaFile, 'utf8').trim().split(/\s+/)[0]
    const actual = await sha256File(file)
    if (expected && expected.toLowerCase() !== actual.toLowerCase()) problems.push('sha256 does not match the .sha256 sidecar (corrupted or tampered)')
    else notes.push('sha256 matches sidecar')
  } else notes.push('no .sha256 sidecar (skipped)')

  return { ok: problems.length === 0, problems, notes }
}

// CLI entry — runs only when invoked directly (so tests can import cleanly).
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const path = process.argv[2]
  if (!path) { console.error('Usage: verify-backup.mjs <path-to-backup.sql.gz>'); process.exit(2) }
  const r = await verifyBackup(path)
  console.log(`backup verify: ${path}`)
  for (const n of r.notes) console.log(`  - ${n}`)
  if (!r.ok) {
    console.error('FAILED:')
    for (const p of r.problems) console.error(`  - ${p}`)
    process.exit(1)
  }
  console.log('  OK — backup integrity and structural completeness verified (not a test restore).')
}
